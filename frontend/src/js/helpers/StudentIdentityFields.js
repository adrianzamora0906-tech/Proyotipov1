const normalize = value => String(value || '').normalize('NFD').replace(/[\u0300-\u036f]/g,'').toLocaleUpperCase('es');
export const findNationalities = query => NATIONALITIES.filter(value=>normalize(value).includes(normalize(query)));
const upperFields = new Set(['firstName','lastName','address','notes','nationality']);

export function bindStudentIdentityFields(form) {
  if (!form || form.dataset.identityFieldsReady) return;
  form.dataset.identityFieldsReady='true';
  const input=form.elements.namedItem('nationality');
  const list=form.querySelector('#student-nationality-options');
  const refresh=()=>{if(list)list.replaceChildren(...findNationalities(input?.value).map(value=>{
    const option=document.createElement('option');option.value=value;return option;
  }));};
  form.addEventListener('input',event=>{
    const field=event.target;
    if(!upperFields.has(field.name)||event.isComposing)return;
    const start=field.selectionStart,end=field.selectionEnd;
    field.value=field.value.toLocaleUpperCase('es');
    if(start!==null)field.setSelectionRange(start,end);
    if(field.name==='nationality')refresh();
  });
  input?.addEventListener('focus',refresh);
  refresh();
}
